#include <stdio.h>

int main() {
    // 题 10: %5d
    int a = 123;
    printf("题10: [%5d]\n", a);

    // 题 11: %-7.2f
    float b = 1234.567;
    printf("题11: [%-7.2f]\n", b);

    // 补充: %-8.2f（宽度8，多1位，看左对齐补空格）
    printf("补充(%-8.2f): [%-8.2f]\n", b, b);

    // 补充: %8.2f（右对齐对照）
    printf("补充(%8.2f):  [%8.2f]\n", b, b);

    // 补充: 验证四舍五入
    float c1 = 1234.564;
    float c2 = 1234.565;
    printf("1234.564 保留2位: %.2f\n", c1);
    printf("1234.565 保留2位: %.2f\n", c2);

    // 补充: %-5d（对照题 10 的左对齐）
    printf("补充(%%-5d): [%-5d]\n", a);

    return 0;
}